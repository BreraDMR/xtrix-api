class PublicBookingCreate(InputModel):
    """Only what a guest may choose. Price, status, payment and tenant ids come from the server."""
    model_config = ConfigDict(extra="forbid")

    service_id: int = Field(..., gt=0)
    staff_id: int = Field(..., gt=0)
    start: UtcDatetime
    full_name: str = Field(..., min_length=1, max_length=255)
    phone: Optional[str] = Field(None, max_length=50)
    email: Optional[EmailStr] = None
    marketing_consent: bool = False
    processing_consent: bool
    client_request_id: str = Field(
        ...,
        min_length=8,
        max_length=64,
        pattern=r"^[A-Za-z0-9_-]+$",
        description="A retry key generated by the booking form",
    )

    @field_validator("phone", mode="before")
    @classmethod
    def clean_phone(cls, value):
        if value is None or value == "":
            return None
        from app.api.core.security import validate_phone

        cleaned = re.sub(r"[\s\-\(\)\.]", "", str(value))
        is_valid, message = validate_phone(cleaned)
        if not is_valid:
            raise invalid("invalid_phone", message)
        return cleaned

    @field_validator("email")
    @classmethod
    def clean_email(cls, value):
        return str(value).strip().lower() if value is not None else None

    @field_validator("marketing_consent", "processing_consent", mode="before")
    @classmethod
    def consent_is_bool(cls, value):
        if not isinstance(value, bool):
            raise invalid("invalid_consent", "Consent must be true or false")
        return value

    @model_validator(mode="after")
    def contact_and_consents(self):
        if any(ord(char) < 32 or ord(char) == 127 for char in self.full_name):
            raise invalid("invalid_name", "The name can't contain line breaks or control characters")
        if bool(self.phone) == bool(self.email):
            raise invalid(
                "contact_choice",
                "Provide exactly one contact: a phone number or an email",
            )
        if not self.processing_consent:
            raise invalid(
                "processing_consent_required",
                "Confirm that the booking data may be processed",
            )
        return self


